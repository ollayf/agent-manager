#!/usr/bin/env python3
"""Render Codex's native config from the shared Claude-format sources (Python 3.8+)."""
import argparse
import json
import math
import os
from pathlib import Path
import re
import shlex
import sys

ROOT = Path(__file__).resolve().parent.parent
LINKS = {"AGENTS.md": "CLAUDE.md", ".agents/skills": "../.claude/skills"}
HEADER = "# GENERATED by scripts/sync_agent_config.py; edit the shared sources, then regenerate.\n"
START = "# >>> shared-agent MCP (generated) >>>"
END = "# <<< shared-agent MCP (generated) <<<"


def managed_config(root, generated):
    """Keep native model/UI settings outside the owned MCP block unchanged."""
    path = root / ".codex/config.toml"
    current = path.read_text() if path.exists() else ""
    if current.startswith(HEADER):
        # Upgrade the previous, explicitly whole-file generated format.
        current = ""
    if START in current or END in current:
        if current.splitlines().count(START) != 1 or current.splitlines().count(END) != 1:
            raise ValueError("Malformed managed MCP block in .codex/config.toml")
        before, rest = current.split(START, 1)
        if END not in rest:
            raise ValueError("Managed MCP block markers are out of order")
        _, after = rest.split(END, 1)
        current = before + after.lstrip("\n")
    if re.search(r"(?m)^\s*(?:\[\[?\s*[\"']?mcp_servers\b|[\"']?mcp_servers[\"']?\s*[.=])", current):
        raise ValueError("Unmanaged MCP config exists; reconcile/import it before generating adapters")
    prefix = current.rstrip("\n")
    return (prefix + "\n\n" if prefix else "") + START + "\n" + generated + END + "\n"


def quoted(value):
    # JSON strings/arrays of strings are also valid TOML and Starlark literals.
    return json.dumps(value, ensure_ascii=False)


def render(root):
    source = json.loads((root / ".mcp.json").read_text())
    if not isinstance(source, dict) or set(source) != {"mcpServers"} or not isinstance(source["mcpServers"], dict):
        raise ValueError(".mcp.json must contain one mcpServers object")
    servers = source["mcpServers"]
    settings = json.loads((root / ".claude/settings.json").read_text())
    permissions = settings.get("permissions", {})
    if set(settings) - {"permissions"} or set(permissions) - {"deny"}:
        raise ValueError("Unsupported shared settings; add an explicit translation before syncing")
    denies = permissions.get("deny", [])
    if not isinstance(denies, list) or not all(isinstance(item, str) for item in denies):
        raise ValueError("permissions.deny must be a list of strings")
    shell_rules, tool_denies = [], {}
    for deny in denies:
        match = re.fullmatch(r"Bash\(([^*]+):\*\)", deny)
        if match:
            prefix = shlex.split(match.group(1))
            if not prefix or any(re.search(r"[^a-zA-Z0-9_./-]", arg) for arg in prefix):
                raise ValueError("Unsupported shell deny prefix: " + deny)
            shell_rules.append('prefix_rule(pattern = %s, decision = "forbidden")' % quoted(prefix))
        elif deny.startswith("mcp__") and "__" in deny[5:]:
            server, tool = deny[5:].rsplit("__", 1)
            tool_denies.setdefault(server, []).append(tool)
        else:
            raise ValueError("Unsupported permission deny: " + deny)

    config = [HEADER.rstrip(), "# Sources: .mcp.json and .claude/settings.json", ""]
    for name, server in sorted(servers.items()):
        if not isinstance(server, dict):
            raise ValueError("MCP server must be an object: " + name)
        kind = server.get("type", "stdio")
        if kind == "stdio":
            allowed = {"type", "command", "args", "env", "cwd"}
            fields = {key: server[key] for key in ("command", "args", "cwd") if key in server}
            if not isinstance(fields.get("command"), str):
                raise ValueError("Missing stdio command: " + name)
        elif kind == "http":
            allowed = {"type", "url", "headers"}
            fields = {"url": server["url"]}
        else:
            raise ValueError("Unsupported MCP transport: " + kind)
        if set(server) - allowed:
            raise ValueError("Unsupported MCP fields for " + name)
        for key, value in fields.items():
            valid = (isinstance(value, list) and all(isinstance(arg, str) for arg in value)) if key == "args" else isinstance(value, str)
            if not valid:
                raise ValueError("Invalid %s for %s" % (key, name))
        for key in ("env", "headers"):
            if key in server and (not isinstance(server[key], dict) or
                                  not all(isinstance(k, str) and isinstance(v, str) for k, v in server[key].items())):
                raise ValueError("%s must map strings to strings: %s" % (key, name))
        # Claude expands these; Codex treats the same strings literally. Shell
        # wrappers in args intentionally expand their own variables at runtime.
        interpolated = [v for k in ("env", "headers") for v in server.get(k, {}).values()]
        interpolated += [server[k] for k in ("url", "command", "cwd") if k in server]
        if any("${" in value for value in interpolated):
            raise ValueError("Claude environment interpolation needs an explicit shared launcher: " + name)
        config.append("[mcp_servers.%s]" % quoted(name))
        for key, value in fields.items():
            config.append("%s = %s" % (key, quoted(value)))
        # Claude's timeout is milliseconds; Codex's tool timeout defaults to only 60s.
        timeout = server.get("env", {}).get("MCP_TOOL_TIMEOUT")
        if timeout is not None:
            seconds = float(timeout) / 1000
            if not math.isfinite(seconds) or seconds <= 0:
                raise ValueError("MCP_TOOL_TIMEOUT must be positive: " + name)
            config.append("tool_timeout_sec = %s" % seconds)
        if name in tool_denies:
            config.append("disabled_tools = " + quoted(tool_denies[name]))
        for source, target in (("env", "env"), ("headers", "http_headers")):
            if source in server:
                config.append("[mcp_servers.%s.%s]" % (quoted(name), target))
                for key, value in sorted(server[source].items()):
                    config.append("%s = %s" % (quoted(key), quoted(value)))
        config.append("")
    # These aliases belong to Claude connectors, not the project MCP servers.
    # Keep their behavioural deny policy in the shared guide; don't create invalid
    # Codex server entries with no command/URL just to attach disabled_tools.
    unmatched = sorted(set(tool_denies) - set(servers))
    if unmatched:
        config.append("# Connector-only deny aliases (shared guide applies): " + ", ".join(unmatched))
    return {
        ".codex/config.toml": managed_config(root, "\n".join(config) + "\n"),
        ".codex/rules/shared.rules": HEADER + "# Source: .claude/settings.json permissions.deny\n" +
        "\n".join(shell_rules) + "\n",
    }


def check_links(root):
    findings = []
    for left, right in (("AGENTS.md", "CLAUDE.md"), (".agents/skills", ".claude/skills")):
        paths = [root / left, root / right]
        if not all(p.exists() for p in paths):
            findings.append("%s and %s must exist (no dangling links)" % (left, right))
        elif not any(p.is_symlink() for p in paths) or not paths[0].samefile(paths[1]):
            findings.append("%s and %s must share one source through a symlink" % (left, right))
        else:
            for path in paths:
                if path.is_symlink() and os.path.isabs(os.readlink(path)):
                    findings.append(str(path.relative_to(root)) + " must use a relative symlink")
    return findings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Read-only drift check")
    parser.add_argument("--root", type=Path, default=ROOT, help="Project root (defaults to this script's parent repo)")
    args = parser.parse_args()
    root = args.root.expanduser().resolve()
    findings = check_links(root)
    try:
        outputs = render(root)
        pending = []
        for name, content in outputs.items():
            path = root / name
            current = path.read_text() if path.exists() else None
            if current != content:
                if args.check:
                    findings.append(name + " is missing or stale")
                elif name.endswith(".rules") and current is not None and not current.startswith(HEADER):
                    findings.append(name + " contains hand-written config; refusing to overwrite")
                else:
                    pending.append((path, content))
        # Preflight every output before writing any of them.
        if not findings:
            for path, content in pending:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        findings.append(str(exc))
    print("MEASURED    %d finding(s)" % len(findings))
    print("REFERENCE   0: shared links intact and Codex config agrees with its sources")
    print("DETAIL      " + ("; ".join(findings) if findings else "instructions, skills, MCP config and shell deny rules agree"))
    print("BLIND SPOT  Does not connect MCP servers or check account authentication. Claude")
    print("            connector aliases have no Codex transport; their denies are behavioural.")
    print("            Native command rules cover matching prefixes, not arbitrary shell scripts.")
    print("DECIDE      " + ("FAIL: repair links or run scripts/sync_agent_config.py" if findings else "PASS: shared agent setup is consistent"))
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
